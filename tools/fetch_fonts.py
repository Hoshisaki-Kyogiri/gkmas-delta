"""Vendor the fonts the web console uses into gkmas_delta/web/fonts/.

The console runs offline, so fonts ship with the app instead of coming from a
CDN. Each family is Fontsource's variable-weight build, pre-sliced by unicode
range: the browser only fetches the slices a page actually needs, even though
all of them sit on disk.

    python tools/fetch_fonts.py

Versions and npm integrity hashes are pinned; a download that doesn't match is
rejected before anything is unpacked.
"""

