import hashlib
import io
import re
import shutil
import sys
import tarfile
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "gkmas_delta" / "web" / "fonts"
VERSION = "5.3.0"

